import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Mapping, Sequence

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tools.recovery_data import Function, RecoveryError, function_text, parse_functions

SCHEMA_VERSION = 1
DEFAULT_MANIFEST = Path("benchmarks/blind_recovery/manifest.json")
DEFAULT_RUN_ROOT = Path("build/blind-recovery")
REPRODUCIBLE = "reproducible"
LEGACY = "legacy-reported"
CASE_STATUSES = {REPRODUCIBLE, LEGACY}


class BenchmarkError(ValueError):
    pass


@dataclass(frozen=True)
class Finding:
    id: str
    category: str
    severity: int
    count: int
    message: str
    lines: tuple[int, ...]
    confidence: str = "medium"

    @property
    def deduction(self) -> int:
        return min(self.severity * self.count, self.severity * 3)


@dataclass(frozen=True)
class Organicity:
    score: int
    rating: str
    findings: tuple[Finding, ...]
    category_deductions: Mapping[str, int]
    human_review_required: bool

    def as_dict(self) -> dict[str, Any]:
        return {
            "score": self.score,
            "rating": self.rating,
            "findings": [
                asdict(item) | {"deduction": item.deduction}
                for item in self.findings
            ],
            "category_deductions": dict(self.category_deductions),
            "human_review_required": self.human_review_required,
        }


@dataclass(frozen=True)
class AssemblyComparison:
    status: str
    exact: bool | None
    similarity: float | None
    target_lines: int
    candidate_lines: int

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class SourceComparison:
    exact_tokens: bool
    token_similarity: float
    reference_tokens: int
    candidate_tokens: int

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


def _now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def _sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_file(path: Path) -> str:
    return _sha256_bytes(path.read_bytes())


def _read_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise BenchmarkError(f"missing JSON file: {path}") from exc
    except json.JSONDecodeError as exc:
        raise BenchmarkError(
            f"invalid JSON {path}:{exc.lineno}:{exc.colno}: {exc.msg}"
        ) from exc
    if not isinstance(value, dict):
        raise BenchmarkError(f"{path}: expected a JSON object")
    return value


def _write_json(path: Path, value: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", dir=path.parent, delete=False
    ) as handle:
        json.dump(value, handle, indent=2, sort_keys=True)
        handle.write("\n")
        temporary = Path(handle.name)
    os.replace(temporary, path)


def _run(root: Path, *args: str, allow_failure: bool = False) -> str:
    process = subprocess.run(
        args,
        cwd=root,
        text=True,
        capture_output=True,
        check=False,
    )
    if process.returncode and not allow_failure:
        raise BenchmarkError(
            process.stderr.strip() or "command failed: " + " ".join(args)
        )
    return process.stdout.strip()


def git_root(path: str | Path | None = None) -> Path:
    start = Path(path or Path.cwd()).resolve()
    relative = _run(start, "git", "rev-parse", "--show-cdup")
    return (start / relative).resolve()


def git_commit(root: Path, value: str = "HEAD") -> str:
    return _run(root, "git", "rev-parse", value)


def _extract_function_text(source: str, symbol: str) -> tuple[Function, str]:
    matches = [item for item in parse_functions(source) if item.symbol == symbol]
    if len(matches) != 1:
        raise BenchmarkError(
            f"function {symbol!r} resolved to {len(matches)} definitions"
        )
    function = matches[0]
    return function, function_text(source, function).rstrip() + "\n"


def extract_function(path: Path, symbol: str) -> tuple[Function, str]:
    return _extract_function_text(path.read_text(encoding="utf-8"), symbol)


def _strip_comments(text: str) -> str:
    out: list[str] = []
    index = 0
    state = "code"
    while index < len(text):
        char = text[index]
        nxt = text[index + 1] if index + 1 < len(text) else ""
        if state == "code":
            if char == "/" and nxt == "/":
                state = "line"
                out.extend("  ")
                index += 2
                continue
            if char == "/" and nxt == "*":
                state = "block"
                out.extend("  ")
                index += 2
                continue
            if char == '"':
                state = "string"
            elif char == "'":
                state = "char"
            out.append(char)
            index += 1
            continue
        if state == "line":
            if char == "\n":
                state = "code"
                out.append(char)
            else:
                out.append(" ")
            index += 1
            continue
        if state == "block":
            if char == "*" and nxt == "/":
                out.extend("  ")
                state = "code"
                index += 2
            else:
                out.append("\n" if char == "\n" else " ")
                index += 1
            continue
        out.append(char)
        if char == "\\" and index + 1 < len(text):
            out.append(text[index + 1])
            index += 2
            continue
        if state == "string" and char == '"':
            state = "code"
        elif state == "char" and char == "'":
            state = "code"
        index += 1
    return "".join(out)


_TOKEN_RE = re.compile(
    r"""
    (?:u8|u16|u32|u64|s8|s16|s32|s64|f32|f64)\b
    |[A-Za-z_]\w*
    |0[xX][0-9A-Fa-f]+(?:[uUlL]+)?
    |(?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?[fFuUlL]*
    |"(?:\\.|[^"\\])*"
    |'(?:\\.|[^'\\])*'
    |<<=|>>=|==|!=|<=|>=|->|\+\+|--|&&|\|\||<<|>>|\+=|-=|\*=|/=|%=|&=|\|=|\^=
    |[{}()\[\];,.?:~!%^&*+\-/|<>=]
    """,
    re.VERBOSE,
)


def c_tokens(text: str) -> list[str]:
    return _TOKEN_RE.findall(_strip_comments(text))


def compare_source(reference: str, candidate: str) -> SourceComparison:
    left = c_tokens(reference)
    right = c_tokens(candidate)
    return SourceComparison(
        exact_tokens=left == right,
        token_similarity=difflib.SequenceMatcher(None, left, right).ratio(),
        reference_tokens=len(left),
        candidate_tokens=len(right),
    )


def normalize_assembly(text: str) -> list[str]:
    ignored = (
        ".file",
        ".ident",
        ".loc",
        ".cfi_",
        ".addrsig",
        ".section .note",
        ".note.GNU-stack",
    )
    lines: list[str] = []
    labels: dict[str, str] = {}

    def label(match: re.Match[str]) -> str:
        raw = match.group(0)
        if raw not in labels:
            labels[raw] = f".L{len(labels)}"
        return labels[raw]

    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith(ignored):
            continue
        line = re.sub(r"\s+#.*$", "", line)
        line = re.sub(r"\s+//.*$", "", line)
        line = re.sub(r"\s+;.*$", "", line)
        if not line:
            continue
        line = re.sub(r"\.L(?:BB|tmp|CPI|JTI)?[A-Za-z0-9_.$]*", label, line)
        line = re.sub(r"\s+", " ", line)
        line = re.sub(r"\s*,\s*", ",", line)
        lines.append(line)
    return lines


def compare_assembly(
    target: str | None, candidate: str | None
) -> AssemblyComparison:
    if target is None or candidate is None:
        return AssemblyComparison("not-run", None, None, 0, 0)
    left = normalize_assembly(target)
    right = normalize_assembly(candidate)
    return AssemblyComparison(
        status="compared",
        exact=left == right,
        similarity=difflib.SequenceMatcher(None, left, right).ratio(),
        target_lines=len(left),
        candidate_lines=len(right),
    )


def _line_numbers(
    text: str, pattern: re.Pattern[str], limit: int = 8
) -> tuple[int, ...]:
    return tuple(
        text.count("\n", 0, match.start()) + 1
        for match in list(pattern.finditer(text))[:limit]
    )


def _finding(
    text: str,
    *,
    finding_id: str,
    category: str,
    severity: int,
    message: str,
    pattern: re.Pattern[str],
    confidence: str = "medium",
) -> Finding | None:
    matches = list(pattern.finditer(text))
    if not matches:
        return None
    return Finding(
        finding_id,
        category,
        severity,
        len(matches),
        message,
        _line_numbers(text, pattern),
        confidence,
    )


