#!/usr/bin/env python3
"""Prepare, freeze, score, archive, and audit blind source-recovery trials.

The benchmark separates four questions that are often conflated:

* Did the candidate reproduce the target assembly?
* Did it resemble the retained source after the blind phase ended?
* Does it look like organic, maintainable C rather than match-shaped scaffolding?
* Is the trial independently replayable from preserved artifacts?

Only the Python standard library is required. Retail or proprietary compiler
steps remain external: callers may supply target/candidate assembly generated by
objdiff, DTK, Metrowerks, Clang, or another controlled toolchain.
"""

