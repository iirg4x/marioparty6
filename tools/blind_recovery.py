def _redundant_drain_condition(text: str) -> Finding | None:
    pattern = re.compile(
        r"""
        while\s*\(\s*
        (?P<expr>[A-Za-z_]\w*(?:(?:->|\.)[A-Za-z_]\w*)*)
        \s*!=\s*0\s*\)\s*\{
        (?P<body>.*?)
        \}\s*
        if\s*\(\s*(?P=expr)\s*==\s*0\s*\)
        """,
        re.DOTALL | re.VERBOSE,
    )
    matches: list[re.Match[str]] = []
    for match in pattern.finditer(text):
        expression = re.escape(match.group("expr"))
        if re.search(
            rf"(?:{expression}\s*--|--\s*{expression}|{expression}\s*-=\s*1)",
            match.group("body"),
        ):
            matches.append(match)
    if not matches:
        return None
    return Finding(
        "guaranteed-post-loop-condition",
        "redundancy",
        4,
        len(matches),
        "Condition is guaranteed after a loop that drains the same value to zero; preserve only with source-shape evidence.",
        tuple(text.count("\n", 0, item.start()) + 1 for item in matches[:8]),
        "medium",
    )


def score_organicity(text: str) -> Organicity:
    cleaned = _strip_comments(text)
    findings: list[Finding] = []
    for finding_id, category, severity, message, pattern, confidence in _ORGANIC_RULES:
        value = _finding(
            cleaned,
            finding_id=finding_id,
            category=category,
            severity=severity,
            message=message,
            pattern=pattern,
            confidence=confidence,
        )
        if value:
            findings.append(value)
    redundant = _redundant_drain_condition(cleaned)
    if redundant:
        findings.append(redundant)
    deductions: dict[str, int] = {}
    for item in findings:
        deductions[item.category] = deductions.get(item.category, 0) + item.deduction
    score = max(0, 100 - sum(deductions.values()))
    high_risk = any(
        item.category == "compiler_control" and item.severity >= 12
        for item in findings
    )
    if score >= 95 and not high_risk:
        rating = "strongly-organic"
    elif score >= 85 and not high_risk:
        rating = "plausibly-organic"
    elif score >= 70:
        rating = "needs-source-shape-review"
    else:
        rating = "match-shaped-or-opaque"
    return Organicity(
        score=score,
        rating=rating,
        findings=tuple(findings),
        category_deductions=deductions,
        human_review_required=bool(findings),
    )


def score_pair(
    reference: str,
    candidate: str,
    *,
    target_assembly: str | None = None,
    candidate_assembly: str | None = None,
) -> dict[str, Any]:
    source = compare_source(reference, candidate)
    assembly = compare_assembly(target_assembly, candidate_assembly)
    reference_organic = score_organicity(reference)
    candidate_organic = score_organicity(candidate)
    reference_ids = {item.id for item in reference_organic.findings}
    candidate_ids = {item.id for item in candidate_organic.findings}
    if assembly.exact is True:
        binary_status = "exact-surrogate-or-target"
    elif assembly.exact is False:
        binary_status = "different"
    else:
        binary_status = "not-run"
    return {
        "schema_version": SCHEMA_VERSION,
        "scored_at": _now(),
        "binary_equivalence": binary_status,
        "source": source.as_dict(),
        "assembly": assembly.as_dict(),
        "organicity": {
            "reference": reference_organic.as_dict(),
            "candidate": candidate_organic.as_dict(),
            "inherited_reference_debt": sorted(reference_ids & candidate_ids),
            "candidate_only_debt": sorted(candidate_ids - reference_ids),
            "reference_only_debt": sorted(reference_ids - candidate_ids),
        },
        "success_dimensions": {
            "assembly_exact": assembly.exact,
            "source_tokens_exact": source.exact_tokens,
            "candidate_organic_score": candidate_organic.score,
            "candidate_organic_rating": candidate_organic.rating,
            "independent_human_review_required": candidate_organic.human_review_required,
        },
    }


def render_score(result: Mapping[str, Any]) -> str:
    source = result.get("source", {})
    assembly = result.get("assembly", {})
    organicity = result.get("organicity", {})
    candidate = (
        organicity.get("candidate", {})
        if isinstance(organicity, Mapping)
        else {}
    )
    inherited = (
        organicity.get("inherited_reference_debt", [])
        if isinstance(organicity, Mapping)
        else []
    )
    only = (
        organicity.get("candidate_only_debt", [])
        if isinstance(organicity, Mapping)
        else []
    )
    lines = [
        "# Blind recovery score",
        "",
        f"- Binary comparison: `{result.get('binary_equivalence')}`",
        f"- Assembly exact: `{assembly.get('exact')}`",
        f"- Assembly similarity: `{assembly.get('similarity')}`",
        f"- Source tokens exact: `{source.get('exact_tokens')}`",
        f"- Source-token similarity: `{source.get('token_similarity')}`",
        f"- Candidate organicity: `{candidate.get('score')}/100` — `{candidate.get('rating')}`",
        f"- Inherited retained-source debt: `{', '.join(inherited) or 'none'}`",
        f"- Candidate-only debt: `{', '.join(only) or 'none'}`",
        "",
        "## Organicity findings",
        "",
    ]
    findings = (
        candidate.get("findings", [])
        if isinstance(candidate, Mapping)
        else []
    )
    if findings:
        for item in findings:
            lines.append(
                f"- `{item.get('id')}` [{item.get('category')}, -{item.get('deduction')}]: "
                f"{item.get('message')} Lines: {item.get('lines')}"
            )
    else:
        lines.append("- None detected by the automated review.")
    lines += [
        "",
        "Automated organicity is a review aid, not proof of historical authenticity. "
        "Exact source similarity can reproduce debt already present in the retained source.",
    ]
    return "\n".join(lines).rstrip() + "\n"


def _load_manifest(root: Path, manifest_path: Path) -> dict[str, Any]:
    path = manifest_path if manifest_path.is_absolute() else root / manifest_path
    value = _read_json(path)
    if value.get("schema_version") != SCHEMA_VERSION:
        raise BenchmarkError(f"{path}: unsupported schema_version")
    cases = value.get("cases")
    if not isinstance(cases, list) or not all(
        isinstance(item, str) for item in cases
    ):
        raise BenchmarkError(f"{path}: cases must be a string list")
    value["_path"] = path
    return value


def _case_paths(root: Path, manifest_path: Path) -> list[Path]:
    manifest = _load_manifest(root, manifest_path)
    base = Path(manifest["_path"]).parent
    return [(base / value).resolve() for value in manifest["cases"]]


def validate_case(
    root: Path, case_path: Path, *, replay: bool = False
) -> tuple[list[str], list[str]]:
    errors: list[str] = []
    warnings: list[str] = []
    case = _read_json(case_path)
    where = (
        case_path.relative_to(root)
        if case_path.is_relative_to(root)
        else case_path
    )
    if case.get("schema_version") != SCHEMA_VERSION:
        errors.append(f"{where}: schema_version must be {SCHEMA_VERSION}")
    status = case.get("status")
    if status not in CASE_STATUSES:
        errors.append(f"{where}: invalid status {status!r}")
    for key in (
        "id",
        "source",
        "function",
        "source_commit",
        "reference_sha256",
    ):
        if not isinstance(case.get(key), str) or not case.get(key):
            errors.append(f"{where}: {key} is required")
    artifacts = case.get("artifacts", {})
    if not isinstance(artifacts, dict):
        errors.append(f"{where}: artifacts must be an object")
        artifacts = {}
    base = case_path.parent
    if status == LEGACY:
        warnings.append(
            f"{where}: legacy result is reported but not independently replayable"
        )
        return errors, warnings
    if re.fullmatch(
        r"[0-9a-f]{64}", str(case.get("reference_sha256", ""))
    ) is None:
        errors.append(
            f"{where}: reproducible case requires a lowercase SHA-256 reference hash"
        )
    required = (
        "evidence",
        "candidate",
        "target_assembly",
        "candidate_assembly",
        "result",
    )
    for key in required:
        relative = artifacts.get(key)
        if not isinstance(relative, str) or not relative:
            errors.append(f"{where}: reproducible case requires artifacts.{key}")
            continue
        candidate = base / relative
        if not candidate.is_file():
            errors.append(f"{where}: missing artifact {relative}")
    candidate_path = base / str(artifacts.get("candidate", ""))
    expected_candidate_hash = case.get("candidate_sha256")
    if candidate_path.is_file() and isinstance(expected_candidate_hash, str):
        actual = sha256_file(candidate_path)
        if actual != expected_candidate_hash:
            errors.append(f"{where}: candidate SHA-256 mismatch")
    blindness = case.get("blindness", {})
    if not isinstance(blindness, dict):
        errors.append(f"{where}: blindness must be an object")
        blindness = {}
    for key in (
        "reference_withheld",
        "candidate_frozen_before_reveal",
        "raw_candidate_preserved",
        "raw_evidence_preserved",
    ):
        if blindness.get(key) is not True:
            errors.append(f"{where}: blindness.{key} must be true")
    if replay and not errors:
        errors.extend(replay_case(root, case_path, write=False))
    return errors, warnings


def audit_repository(
    root: Path,
    manifest_path: Path = DEFAULT_MANIFEST,
    *,
    replay: bool = False,
) -> dict[str, Any]:
    errors: list[str] = []
    warnings: list[str] = []
    identifiers: set[str] = set()
    case_paths = _case_paths(root, manifest_path)
    for path in case_paths:
        if not path.is_file():
            errors.append(f"missing benchmark case: {path}")
            continue
        case = _read_json(path)
        case_id = case.get("id")
        if isinstance(case_id, str):
            if case_id in identifiers:
                errors.append(f"duplicate benchmark case id: {case_id}")
            identifiers.add(case_id)
        case_errors, case_warnings = validate_case(
            root, path, replay=replay
        )
        errors.extend(case_errors)
        warnings.extend(case_warnings)
    return {
        "schema_version": SCHEMA_VERSION,
        "manifest": str(manifest_path),
        "cases": len(case_paths),
        "errors": sorted(set(errors)),
        "warnings": sorted(set(warnings)),
        "replay": replay,
    }


def _git_show_function(
    root: Path, commit: str, source: str, symbol: str
) -> str:
    text = _run(root, "git", "show", f"{commit}:{source}")
    _, value = _extract_function_text(text, symbol)
    return value


def replay_case(
    root: Path, case_path: Path, *, write: bool = False
) -> list[str]:
    case = _read_json(case_path)
    if case.get("status") != REPRODUCIBLE:
        return [f"{case_path}: legacy case cannot be replayed"]
    artifacts = case["artifacts"]
    base = case_path.parent
    reference = _git_show_function(
        root,
        str(case["source_commit"]),
        str(case["source"]),
        str(case["function"]),
    )
    if _sha256_bytes(reference.encode()) != case.get("reference_sha256"):
        return [f"{case_path}: reference SHA-256 mismatch at source commit"]
    candidate = (base / artifacts["candidate"]).read_text(encoding="utf-8")
    target_assembly = (base / artifacts["target_assembly"]).read_text(
        encoding="utf-8"
    )
    candidate_assembly = (base / artifacts["candidate_assembly"]).read_text(
        encoding="utf-8"
    )
    actual = score_pair(
        reference,
        candidate,
        target_assembly=target_assembly,
        candidate_assembly=candidate_assembly,
    )
    stored = _read_json(base / artifacts["result"])
    comparable_keys = (
        "binary_equivalence",
        "source",
        "assembly",
        "organicity",
        "success_dimensions",
    )
    errors = [
        f"{case_path}: replay differs for {key}"
        for key in comparable_keys
        if actual.get(key) != stored.get(key)
    ]
    if write and not errors:
        _write_json(base / artifacts["result"], actual)
        report = artifacts.get("report")
        if isinstance(report, str):
            (base / report).write_text(
                render_score(actual), encoding="utf-8"
            )
    return errors


def prepare_run(
    root: Path,
    *,
    trial_id: str,
    source_path: str,
    symbol: str,
    evidence_path: Path,
    target_assembly_path: Path,
    run_dir: Path | None = None,
) -> Path:
    source = root / source_path
    if not source.is_file():
        raise BenchmarkError(f"missing source: {source}")
    if not evidence_path.is_file():
        raise BenchmarkError(f"missing evidence: {evidence_path}")
    if not target_assembly_path.is_file():
        raise BenchmarkError(f"missing target assembly: {target_assembly_path}")
    function, reference = extract_function(source, symbol)
    destination = run_dir or (
        root
        / DEFAULT_RUN_ROOT
        / f"{trial_id}-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}"
    )
    destination = destination.resolve()
    if destination.exists() and any(destination.iterdir()):
        raise BenchmarkError(f"run directory is not empty: {destination}")
    private = destination / "private"
    packet = destination / "packet"
    private.mkdir(parents=True, exist_ok=True)
    packet.mkdir(parents=True, exist_ok=True)
    (private / "reference.c").write_text(reference, encoding="utf-8")
    shutil.copy2(evidence_path, packet / "evidence.md")
    shutil.copy2(target_assembly_path, packet / "target.s")
    signature = function.signature.rstrip(";") + ";\n"
    (packet / "signature.h").write_text(signature, encoding="utf-8")
    (destination / "candidate.c").write_text(
        signature.rstrip(";\n")
        + "\n{\n    /* Blind candidate goes here. */\n}\n",
        encoding="utf-8",
    )
    seal = {
        "schema_version": SCHEMA_VERSION,
        "id": trial_id,
        "source": source_path,
        "function": symbol,
        "source_commit": git_commit(root),
        "reference_sha256": _sha256_bytes(reference.encode()),
        "evidence_sha256": sha256_file(packet / "evidence.md"),
        "target_assembly_sha256": sha256_file(packet / "target.s"),
        "created_at": _now(),
        "candidate_frozen": False,
    }
    _write_json(destination / "seal.json", seal)
    return destination


def freeze_candidate(
    run_dir: Path, candidate_path: Path, *, force: bool = False
) -> dict[str, Any]:
    seal_path = run_dir / "seal.json"
    seal = _read_json(seal_path)
    frozen_path = run_dir / "frozen-candidate.c"
    metadata_path = run_dir / "candidate.json"
    if metadata_path.exists() and not force:
        raise BenchmarkError(
            "candidate is already frozen; use --force to replace"
        )
    if not candidate_path.is_file():
        raise BenchmarkError(f"missing candidate: {candidate_path}")
    shutil.copy2(candidate_path, frozen_path)
    metadata = {
        "schema_version": SCHEMA_VERSION,
        "candidate_sha256": sha256_file(frozen_path),
        "frozen_at": _now(),
        "candidate_path": frozen_path.name,
    }
    _write_json(metadata_path, metadata)
    seal["candidate_frozen"] = True
    seal["candidate_sha256"] = metadata["candidate_sha256"]
    seal["candidate_frozen_at"] = metadata["frozen_at"]
    _write_json(seal_path, seal)
    return metadata


def score_run(
    run_dir: Path,
    *,
    candidate_assembly_path: Path | None = None,
) -> dict[str, Any]:
    seal = _read_json(run_dir / "seal.json")
    candidate_meta = _read_json(run_dir / "candidate.json")
    if seal.get("candidate_frozen") is not True:
        raise BenchmarkError("candidate must be frozen before scoring")
    candidate_path = run_dir / str(candidate_meta["candidate_path"])
    if sha256_file(candidate_path) != candidate_meta.get("candidate_sha256"):
        raise BenchmarkError("frozen candidate changed after freeze")
    reference = (run_dir / "private/reference.c").read_text(encoding="utf-8")
    if _sha256_bytes(reference.encode()) != seal.get("reference_sha256"):
        raise BenchmarkError("private reference does not match seal")
    target_assembly = (run_dir / "packet/target.s").read_text(
        encoding="utf-8"
    )
    candidate_assembly = (
        candidate_assembly_path.read_text(encoding="utf-8")
        if candidate_assembly_path and candidate_assembly_path.is_file()
        else None
    )
    result = score_pair(
        reference,
        candidate_path.read_text(encoding="utf-8"),
        target_assembly=target_assembly,
        candidate_assembly=candidate_assembly,
    )
    result.update(
        {
            "id": seal.get("id"),
            "target_source": seal.get("source"),
            "function": seal.get("function"),
            "source_commit": seal.get("source_commit"),
            "reference_sha256": seal.get("reference_sha256"),
            "candidate_sha256": candidate_meta.get("candidate_sha256"),
            "candidate_frozen_at": candidate_meta.get("frozen_at"),
            "blindness": {
                "reference_withheld": True,
                "candidate_frozen_before_reveal": True,
                "raw_candidate_preserved": True,
                "raw_evidence_preserved": True,
            },
        }
    )
    _write_json(run_dir / "result.json", result)
    (run_dir / "report.md").write_text(
        render_score(result), encoding="utf-8"
    )
    return result


def archive_run(root: Path, run_dir: Path, destination: Path) -> Path:
    seal = _read_json(run_dir / "seal.json")
    candidate_meta = _read_json(run_dir / "candidate.json")
    result = _read_json(run_dir / "result.json")
    candidate_assembly = run_dir / "candidate.s"
    if not candidate_assembly.is_file():
        raise BenchmarkError(
            "candidate.s is required before archival; preserve the exact assembly compared"
        )
    destination = (
        destination if destination.is_absolute() else root / destination
    )
    if destination.exists() and any(destination.iterdir()):
        raise BenchmarkError(
            f"archive destination is not empty: {destination}"
        )
    destination.mkdir(parents=True, exist_ok=True)
    shutil.copy2(
        run_dir / "packet/evidence.md", destination / "evidence.md"
    )
    shutil.copy2(run_dir / "packet/target.s", destination / "target.s")
    shutil.copy2(
        run_dir / str(candidate_meta["candidate_path"]),
        destination / "candidate.c",
    )
    shutil.copy2(candidate_assembly, destination / "candidate.s")
    _write_json(destination / "result.json", result)
    (destination / "report.md").write_text(
        render_score(result), encoding="utf-8"
    )
    case = {
        "schema_version": SCHEMA_VERSION,
        "id": seal["id"],
        "status": REPRODUCIBLE,
        "source": seal["source"],
        "function": seal["function"],
        "source_commit": seal["source_commit"],
        "reference_sha256": seal["reference_sha256"],
        "candidate_sha256": candidate_meta["candidate_sha256"],
        "artifacts": {
            "evidence": "evidence.md",
            "candidate": "candidate.c",
            "target_assembly": "target.s",
            "candidate_assembly": "candidate.s",
            "result": "result.json",
            "report": "report.md",
        },
        "blindness": result.get("blindness", {}),
        "archived_at": _now(),
    }
    _write_json(destination / "case.json", case)
    return destination / "case.json"


def _print_audit(value: Mapping[str, Any]) -> None:
    print(f"blind benchmark cases: {value.get('cases', 0)}")
    for error in value.get("errors", []):
        print(f"ERROR: {error}")
    for warning in value.get("warnings", []):
        print(f"WARN: {warning}")
    if not value.get("errors"):
        print("blind benchmark audit: PASS")


def _resolve(root: Path, value: str | Path) -> Path:
    path = Path(value).expanduser()
    return (path if path.is_absolute() else root / path).resolve()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root")
    sub = parser.add_subparsers(dest="command", required=True)

    audit = sub.add_parser(
        "audit", help="validate preserved benchmark cases"
    )
    audit.add_argument("--manifest", default=str(DEFAULT_MANIFEST))
    audit.add_argument("--replay", action="store_true")
    audit.add_argument("--strict", action="store_true")
    audit.add_argument("--json", action="store_true")

    organicity = sub.add_parser(
        "organicity", help="score organic-source indicators"
    )
    organicity.add_argument("path")
    organicity.add_argument("--function")
    organicity.add_argument("--json", action="store_true")

    score = sub.add_parser(
        "score", help="score one reference/candidate pair"
    )
    score.add_argument("--reference", required=True)
    score.add_argument("--candidate", required=True)
    score.add_argument("--function")
    score.add_argument("--target-assembly")
    score.add_argument("--candidate-assembly")
    score.add_argument("--output")

    prepare = sub.add_parser(
        "prepare", help="create a sealed local holdout run"
    )
    prepare.add_argument("--id", required=True)
    prepare.add_argument("--source", required=True)
    prepare.add_argument("--function", required=True)
    prepare.add_argument("--evidence", required=True)
    prepare.add_argument("--target-assembly", required=True)
    prepare.add_argument("--run-dir")

    freeze = sub.add_parser(
        "freeze", help="freeze a candidate before reveal/scoring"
    )
    freeze.add_argument("--run-dir", required=True)
    freeze.add_argument("--candidate", required=True)
    freeze.add_argument("--force", action="store_true")

    score_run_parser = sub.add_parser(
        "score-run", help="score a frozen holdout run"
    )
    score_run_parser.add_argument("--run-dir", required=True)
    score_run_parser.add_argument("--candidate-assembly")

    archive = sub.add_parser(
        "archive", help="archive a replayable completed run"
    )
    archive.add_argument("--run-dir", required=True)
    archive.add_argument("--destination", required=True)

    replay = sub.add_parser("replay", help="replay one archived case")
    replay.add_argument("case")

    args = parser.parse_args()
    try:
        root = git_root(args.root)
        if args.command == "audit":
            value = audit_repository(
                root,
                Path(args.manifest),
                replay=args.replay,
            )
            if args.json:
                print(json.dumps(value, indent=2))
            else:
                _print_audit(value)
            failed = bool(value["errors"]) or (
                args.strict and bool(value["warnings"])
            )
            return 1 if failed else 0
        if args.command == "organicity":
            path = _resolve(root, args.path)
            text = path.read_text(encoding="utf-8")
            if args.function:
                _, text = _extract_function_text(text, args.function)
            value = score_organicity(text).as_dict()
            if args.json:
                print(json.dumps(value, indent=2))
            else:
                print(
                    f"organicity: {value['score']}/100 ({value['rating']})"
                )
                for item in value["findings"]:
                    print(
                        f"- {item['id']}: {item['message']} lines={item['lines']}"
                    )
            return 0
        if args.command == "score":
            reference_path = _resolve(root, args.reference)
            candidate_path = _resolve(root, args.candidate)
            reference = reference_path.read_text(encoding="utf-8")
            candidate = candidate_path.read_text(encoding="utf-8")
            if args.function:
                _, reference = _extract_function_text(
                    reference, args.function
                )
                _, candidate = _extract_function_text(
                    candidate, args.function
                )
            target_assembly = (
                _resolve(root, args.target_assembly).read_text(
                    encoding="utf-8"
                )
                if args.target_assembly
                else None
            )
            candidate_assembly = (
                _resolve(root, args.candidate_assembly).read_text(
                    encoding="utf-8"
                )
                if args.candidate_assembly
                else None
            )
            result = score_pair(
                reference,
                candidate,
                target_assembly=target_assembly,
                candidate_assembly=candidate_assembly,
            )
            if args.output:
                output = _resolve(root, args.output)
                _write_json(output, result)
                output.with_suffix(".md").write_text(
                    render_score(result), encoding="utf-8"
                )
                print(f"wrote {output}")
            else:
                print(json.dumps(result, indent=2))
            return 0
        if args.command == "prepare":
            destination = prepare_run(
                root,
                trial_id=args.id,
                source_path=args.source,
                symbol=args.function,
                evidence_path=_resolve(root, args.evidence),
                target_assembly_path=_resolve(
                    root, args.target_assembly
                ),
                run_dir=(
                    _resolve(root, args.run_dir)
                    if args.run_dir
                    else None
                ),
            )
            print(destination)
            return 0
        if args.command == "freeze":
            value = freeze_candidate(
                _resolve(root, args.run_dir),
                _resolve(root, args.candidate),
                force=args.force,
            )
            print(json.dumps(value, indent=2))
            return 0
        if args.command == "score-run":
            run_dir = _resolve(root, args.run_dir)
            assembly = (
                _resolve(root, args.candidate_assembly)
                if args.candidate_assembly
                else None
            )
            if assembly:
                shutil.copy2(assembly, run_dir / "candidate.s")
            result = score_run(
                run_dir, candidate_assembly_path=assembly
            )
            print(render_score(result), end="")
            return 0
        if args.command == "archive":
            value = archive_run(
                root,
                _resolve(root, args.run_dir),
                Path(args.destination),
            )
            print(value)
            return 0
        errors = replay_case(
            root, _resolve(root, args.case), write=False
        )
        for error in errors:
            print(f"ERROR: {error}")
        if not errors:
            print("blind benchmark replay: PASS")
        return 1 if errors else 0
    except (BenchmarkError, OSError, RecoveryError) as exc:
        print(f"error: {exc}")
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
